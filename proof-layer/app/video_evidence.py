def register(db: Session, household: Household, device: Device, *, source: Path, source_kind: str,
             provenance: dict[str, Any], limits: Optional[vp.Limits] = None) -> tuple[VideoAsset, bool]:
    """Store a validated clip for one camera, video only. Idempotent per
    household and source file: the same bytes return the same asset."""
    try:
        probe = vp.inspect(source, limits or upload_limits())
    except vp.MediaError as exc:
        raise _media_error(exc)
    source_sha = vp.sha256_file(source)
    # One clip per household and source file, decided under a lock on that
    # file's hash, so concurrent imports of the same bytes make one asset.
    db.execute(select(func.pg_advisory_xact_lock(func.hashtext(f"{household.id}:{source_sha}"))))
    existing = db.execute(select(VideoAsset).where(VideoAsset.household_id == household.id,
                                                   VideoAsset.source_sha256 == source_sha)).scalar_one_or_none()
    if existing is not None:
        if existing.deleted_at is not None:
            raise DomainError(409, "ASSET_DELETED", "this clip was deleted from this family's account")
        return existing, False
    ext = ".webm" if probe["family"] == "matroska" else ".mp4"
    # Stored without audio: the evidence is the picture, and a nursery's sound
    # isn't needed for it (review, 2026-10-11). A remux, not a re-encode.
    media_root().mkdir(parents=True, exist_ok=True)
    tmp = media_root() / f"incoming-{uuid.uuid4().hex}{ext}"
    try:
        vp.video_only_copy(source, tmp)
        sha = vp.sha256_file(tmp)
        key = f"{sha}{ext}"
        target = media_root() / key
        if not target.is_file():
            tmp.replace(target)
    finally:
        tmp.unlink(missing_ok=True)
    asset = VideoAsset(id=new_id("vas"), household_id=household.id, device_id=device.id, source_kind=source_kind,
                       storage_key=key, source_sha256=source_sha, sha256=sha, size_bytes=target.stat().st_size,
                       container=probe["container"],
                       codec=probe["codec"], width=probe["width"], height=probe["height"], fps=probe["fps"],
                       duration_s=probe["duration_s"],
                       provenance=provenance | {"source_sha256": source_sha, "audio_in_source": probe["has_audio"],
                                                "audio_stored": False},
                       retention_until=utcnow() + RETENTION)
    db.add(asset)
    db.flush()
    return asset, True


def request_analysis(db: Session, household: Household, asset: VideoAsset,
                     config: vp.Config = vp.Config()) -> tuple[VideoAnalysisRun, bool]:
    """One run per (clip, processor version, config), and one outbox job per
    run. A repeated or concurrent request returns the same run."""
    if asset.deleted_at is not None:
        raise DomainError(409, "ASSET_DELETED", "this clip was deleted")
    digest = config.digest()
    inserted = db.execute(pg_insert(VideoAnalysisRun).values(
        id=new_id("var"), household_id=household.id, asset_id=asset.id, processor_version=vp.PROCESSOR_VERSION,
        config_digest=digest, config=asdict(config), input_sha256=asset.sha256, trace_id=current_trace_id())
        .on_conflict_do_nothing(constraint="uq_video_runs_identity").returning(VideoAnalysisRun.id)).scalar_one_or_none()
    run = db.execute(select(VideoAnalysisRun).where(
        VideoAnalysisRun.asset_id == asset.id, VideoAnalysisRun.processor_version == vp.PROCESSOR_VERSION,
        VideoAnalysisRun.config_digest == digest)).scalar_one()
    db.execute(pg_insert(OutboxJob).values(household_id=household.id, kind="analyze_video",
                                           dedupe_key=f"video:{run.id}", payload={"run_id": run.id},
                                           trace_id=current_trace_id())
               .on_conflict_do_nothing(constraint="uq_outbox_dedupe"))
    return run, inserted is not None


def retry(db: Session, run: VideoAnalysisRun) -> VideoAnalysisRun:
    """Re-queue a failed run on the same record and the same job."""
    if run.state != "FAILED":
        raise DomainError(409, "RUN_NOT_FAILED", "only a failed analysis can be retried", state=run.state)
    run.state, run.error_code, run.error_detail, run.updated_at = "REGISTERED", None, None, func.now()
    run.attempts = 0
    job = db.execute(select(OutboxJob).where(OutboxJob.dedupe_key == f"video:{run.id}")
                     .with_for_update()).scalar_one()
    job.state, job.available_at, job.lease_until, job.last_error = "pending", func.now(), None, None
    job.attempts = 0
    return run


# ---------------------------------------------------------------- the worker's side

def _fail(run_id: str, code: str, detail: dict[str, Any]) -> None:
    with transaction() as db:
        run = db.execute(select(VideoAnalysisRun).where(VideoAnalysisRun.id == run_id).with_for_update()).scalar_one()
        if run.state == "COMPLETED":
            return
        run.state, run.error_code, run.error_detail = "FAILED", code, detail
        run.finished_at = run.updated_at = func.now()
        growth.record_server(db, "video_analysis_failed", run.household_id, {"run_id": run.id, "code": code})


def _advance(run_id: str, attempt: int, to_state: str) -> bool:
    """Move this attempt's run on, only if it is still this attempt's: a
    worker whose lease was taken over never writes over the newer one."""
    with transaction() as db:
        run = db.execute(select(VideoAnalysisRun).where(VideoAnalysisRun.id == run_id).with_for_update()).scalar_one()
        if run.attempts != attempt or run.state not in ("VALIDATING", "ANALYZING"):
            return False
        run.state, run.updated_at = to_state, func.now()
        return True


def process(run_id: str, *, on_frame: Any = None, heartbeat: Any = None) -> str:
    """Advance one run to COMPLETED or FAILED. Safe to repeat and safe to race:
    each attempt numbers itself, every later write checks that number under a
    row lock, and a run that has crashed its worker MAX_RUN_ATTEMPTS times is
    failed instead of retried forever. `heartbeat()` is called while decoding
    so the worker can extend its lease."""
    with transaction() as db:
        run = db.execute(select(VideoAnalysisRun).where(VideoAnalysisRun.id == run_id).with_for_update()).scalar_one()
        if run.state in ("COMPLETED", "FAILED"):
            return run.state
        if run.attempts >= MAX_RUN_ATTEMPTS:
            run.state, run.error_code = "FAILED", "WORKER_GAVE_UP"
            run.error_detail = {"attempts": run.attempts, "message": "the worker stopped during this clip repeatedly"}
            run.finished_at = run.updated_at = func.now()
            growth.record_server(db, "video_analysis_failed", run.household_id, {"run_id": run.id, "code": "WORKER_GAVE_UP"})
            return "FAILED"
        asset = db.get(VideoAsset, run.asset_id)
        run.state, run.attempts, run.updated_at = "VALIDATING", run.attempts + 1, func.now()
        run.started_at = run.started_at or func.now()
        attempt = run.attempts
        deleted, key, sha, config = asset.deleted_at is not None, asset.storage_key, run.input_sha256, dict(run.config)
        household_id, asset_id = run.household_id, asset.id
    if deleted:
        _fail(run_id, "ASSET_DELETED", {})
        return "FAILED"
    path = media_root() / key
    if not path.is_file():
        _fail(run_id, "MEDIA_UNAVAILABLE", {"storage_key": key})
        return "FAILED"
    if vp.sha256_file(path) != sha:
        _fail(run_id, "HASH_MISMATCH", {})
        return "FAILED"
    if not _advance(run_id, attempt, "ANALYZING"):
        return "SUPERSEDED"
    last_beat = [time.monotonic()]

    def tick(n: int) -> None:
        if heartbeat is not None and time.monotonic() - last_beat[0] > HEARTBEAT_S:
            heartbeat()
            last_beat[0] = time.monotonic()
        if on_frame is not None:
            on_frame(n)
    try:
        result = vp.analyze(path, vp.Config(**config), on_frame=tick)
    except vp.MediaError as exc:
        _fail(run_id, exc.code, {"message": exc.message} | {k: v for k, v in exc.detail.items()
                                                            if isinstance(v, (int, float, str))})
        return "FAILED"
    with transaction() as db:
        run = db.execute(select(VideoAnalysisRun).where(VideoAnalysisRun.id == run_id).with_for_update()).scalar_one()
        if run.state != "ANALYZING" or run.attempts != attempt:
            return run.state                       # another attempt owns this run now
        for seq, i in enumerate(result["intervals"]):
            db.add(VideoObservation(id=new_id("vob"), household_id=household_id, run_id=run_id, seq=seq, kind=i["kind"],
                                    reason=i["reason"], t_start=i["t_start"], t_end=i["t_end"], windows=i["windows"],
                                    frames=i["frames"], coverage_min=i["coverage_min"],
                                    local_change_mean=i["local_change_mean"], local_change_max=i["local_change_max"],
                                    brightness_mean=i["brightness_mean"]))
        run.state, run.finished_at, run.updated_at = "COMPLETED", func.now(), func.now()
        run.summary = {k: result[k] for k in ("input", "frames", "library", "config_digest", "processor_version")}
        run.windows, run.frame_samples, run.elapsed_ms = result["windows"], result["frame_samples"], result["elapsed_ms"]
        asset = db.execute(select(VideoAsset).where(VideoAsset.id == asset_id).with_for_update()).scalar_one()
        asset.evidence_revision += 1
        if asset.duration_s is None:               # a stream written without a duration header
            asset.duration_s = result["frames"]["measured_duration_s"]
        growth.record_server(db, "video_analysis_completed", household_id,
                             {"run_id": run_id, "elapsed_ms": int(result["elapsed_ms"]),
                              "intervals": len(result["intervals"]),
                              "insufficient": sum(1 for i in result["intervals"]
                                                  if i["kind"] in ("insufficient_evidence", "low_quality"))})
    return "COMPLETED"


# ---------------------------------------------------------------- the family's side

def latest_run(db: Session, asset: VideoAsset) -> Optional[VideoAnalysisRun]:
    return db.execute(select(VideoAnalysisRun).where(VideoAnalysisRun.asset_id == asset.id)
                      .order_by(VideoAnalysisRun.created_at.desc(), VideoAnalysisRun.id.desc()).limit(1)
                      ).scalar_one_or_none()


def _overlaps(a0: float, a1: float, b0: float, b1: float) -> bool:
    return a0 < b1 and b0 < a1


def _observation_view(o: VideoObservation) -> dict[str, Any]:
    return {"id": o.id, "seq": o.seq, "kind": o.kind, "reason": o.reason, "t_start": o.t_start, "t_end": o.t_end,
            "frames": o.frames, "windows": o.windows, "coverage_min": o.coverage_min,
            "local_change_mean": o.local_change_mean, "local_change_max": o.local_change_max,
            "brightness_mean": o.brightness_mean, "source": "computer_measured", "says": KIND_TEXT[o.kind]}


def view(db: Session, principal: Principal, household: Household, asset: VideoAsset) -> dict[str, Any]:
    """Everything the evidence screen shows, from stored rows. Read-only
    apart from the access record."""
    device = db.get(Device, asset.device_id)
    g = require_gate(db, household, device, record=False)
    run = latest_run(db, asset)
    observations = list(db.execute(select(VideoObservation).where(VideoObservation.run_id == run.id)
                                   .order_by(VideoObservation.seq)).scalars()) if run else []
    annotations = list(db.execute(select(VideoAnnotation).where(VideoAnnotation.asset_id == asset.id)
                                  .order_by(VideoAnnotation.revision)).scalars())
    names = {m.id: m.display_name for m in db.execute(select(Member).where(Member.household_id == household.id)).scalars()}
    superseded = {a.supersedes_annotation_id: a.id for a in annotations if a.supersedes_annotation_id}
    acks = db.execute(select(VideoAcknowledgment.member_id, func.max(VideoAcknowledgment.revision))
                      .where(VideoAcknowledgment.asset_id == asset.id).group_by(VideoAcknowledgment.member_id)).all()
    return {
        "asset": asset_view(asset), "gate": g, "evidence_revision": asset.evidence_revision,
        "run": run_view(run),
        "observations": [_observation_view(o) for o in observations],
        "annotations": [{"id": a.id, "revision": a.revision, "label": a.label, "says": LABEL_TEXT[a.label],
                         "t_start": a.t_start, "t_end": a.t_end, "author": names.get(a.member_id, "A member"),
                         "author_id": a.member_id, "source": "parent_reported",
                         "supersedes": a.supersedes_annotation_id, "superseded_by": superseded.get(a.id),
                         "contradicts": [o.id for o in observations if o.kind in CONTRADICTS.get(a.label, ())
                                         and _overlaps(a.t_start, a.t_end, o.t_start, o.t_end)],
                         "at": a.created_at.isoformat()} for a in annotations],
        "acknowledgments": [{"member_id": m, "name": names.get(m, "A member"), "revision": r,
                             "changed_since": r < asset.evidence_revision} for m, r in acks],
        "viewer": {"member_id": principal.member_id, "can_annotate": principal.role in ("owner", "admin", "caregiver")},
        "not_claimed": ["sleep or wake state", "breathing", "health or safety", "who or what moved"],
    }


def asset_view(a: VideoAsset) -> dict[str, Any]:
    return {"id": a.id, "device_id": a.device_id, "source_kind": a.source_kind, "sha256": a.sha256,
            "size_bytes": a.size_bytes, "container": a.container, "codec": a.codec, "width": a.width,
            "height": a.height, "fps": a.fps, "duration_s": a.duration_s, "provenance": a.provenance,
            "retention_until": a.retention_until.isoformat(), "deleted": a.deleted_at is not None,
            "created_at": a.created_at.isoformat()}


def run_view(r: Optional[VideoAnalysisRun]) -> Optional[dict[str, Any]]:
    if r is None:
        return None
    return {"id": r.id, "state": r.state, "processor_version": r.processor_version, "config_digest": r.config_digest,
            "config": r.config, "input_sha256": r.input_sha256, "attempts": r.attempts, "error_code": r.error_code,
            "error_detail": r.error_detail, "summary": r.summary, "windows": r.windows,
            "frame_samples": r.frame_samples, "elapsed_ms": r.elapsed_ms, "trace_id": r.trace_id,
            "started_at": r.started_at.isoformat() if r.started_at else None,
            "finished_at": r.finished_at.isoformat() if r.finished_at else None}


def _interval_snapshot(db: Session, asset: VideoAsset, t0: float, t1: float) -> dict[str, Any]:
    run = latest_run(db, asset)
    obs = [o for o in db.execute(select(VideoObservation).where(VideoObservation.run_id == run.id)).scalars()
           if _overlaps(t0, t1, o.t_start, o.t_end)] if run else []
    every = list(db.execute(select(VideoAnnotation).where(VideoAnnotation.asset_id == asset.id)).scalars())
    # A corrected report is history, not a current one (bug hunt, 2026-10-12:
    # "After" listed both the replaced report and its correction).
    replaced = {a.supersedes_annotation_id for a in every if a.supersedes_annotation_id}
    notes = [a for a in every if a.id not in replaced and _overlaps(t0, t1, a.t_start, a.t_end)]
    return {"revision": asset.evidence_revision,
            "measured": [{"kind": o.kind, "t_start": o.t_start, "t_end": o.t_end} for o in sorted(obs, key=lambda o: o.seq)],
            "reported": [{"label": a.label, "revision": a.revision, "t_start": a.t_start, "t_end": a.t_end}
                         for a in sorted(notes, key=lambda a: a.revision)]}


def annotate(db: Session, principal: Principal, household: Household, asset: VideoAsset, *, label: str,
             t_start: float, t_end: float, expected_revision: int, client_ref: str,
             supersedes: Optional[str] = None) -> tuple[dict[str, Any], bool]:
    """Add what a person reports about an interval as a new evidence revision.
    The measurement is never changed. Caller holds the household lock and has
    locked the asset row."""
    request_hash = hashlib.sha256(repr((asset.id, label, round(t_start, 3), round(t_end, 3), supersedes,
                                        principal.member_id)).encode()).hexdigest()
    prior = db.execute(select(VideoAnnotation).where(VideoAnnotation.household_id == household.id,
                                                     VideoAnnotation.client_ref == client_ref)).scalar_one_or_none()
    if prior is not None:
        if prior.request_hash != request_hash:
            raise DomainError(409, "IDEMPOTENCY_KEY_REUSED", "this key was used for a different annotation")
        return {"annotation_id": prior.id, "revision": prior.revision, "replayed": True}, True
    if label not in LABELS:
        raise DomainError(422, "UNKNOWN_LABEL", "unknown annotation label", allowed=list(LABELS))
    if asset.evidence_revision < 1:
        raise DomainError(409, "ANALYSIS_NOT_COMPLETE", "annotate after the analysis has completed")
    duration = asset.duration_s or 0.0
    if not (0 <= t_start < t_end <= duration + 1e-6):
        raise DomainError(422, "INTERVAL_OUT_OF_RANGE", "the interval must lie within the clip",
                          duration_s=duration)
    if expected_revision != asset.evidence_revision:
        raise DomainError(409, "STALE_EVIDENCE_VIEW", "the evidence changed since this screen loaded",
                          current_revision=asset.evidence_revision)
    if supersedes is not None:
        old = db.execute(select(VideoAnnotation).where(VideoAnnotation.household_id == household.id,
                                                       VideoAnnotation.asset_id == asset.id,
                                                       VideoAnnotation.id == supersedes)).scalar_one_or_none()
        if old is None:
            raise DomainError(404, "NOT_FOUND", "annotation not found")
        if old.member_id != principal.member_id:
            raise DomainError(403, "NOT_YOUR_REPORT", "only the person who made a report can correct it; add your own")
        if db.execute(select(VideoAnnotation.id).where(VideoAnnotation.supersedes_annotation_id == supersedes)).first():
            raise DomainError(409, "ALREADY_CORRECTED", "this annotation was already corrected; correct the newer one")
    before = _interval_snapshot(db, asset, t_start, t_end)
    asset.evidence_revision += 1
    note = VideoAnnotation(id=new_id("van"), household_id=household.id, asset_id=asset.id,
                           member_id=principal.member_id, client_ref=client_ref, request_hash=request_hash,
                           revision=asset.evidence_revision, label=label, t_start=t_start, t_end=t_end,
                           supersedes_annotation_id=supersedes, trace_id=current_trace_id())
    db.add(note)
    db.flush()
    after = _interval_snapshot(db, asset, t_start, t_end)
    growth.record_server(db, "video_annotation_added", household.id,
                         {"asset_id": asset.id, "label": label, "correction": supersedes is not None})
    return {"annotation_id": note.id, "revision": note.revision, "replayed": False, "before": before,
            "after": after, "measurement_changed": False}, False


def acknowledge(db: Session, principal: Principal, asset: VideoAsset, revision: int) -> dict[str, Any]:
    if not 1 <= revision <= asset.evidence_revision:
        raise DomainError(422, "UNKNOWN_REVISION", "no such evidence revision", current_revision=asset.evidence_revision)
    db.execute(pg_insert(VideoAcknowledgment).values(id=new_id("vak"), household_id=asset.household_id,
                                                     asset_id=asset.id, member_id=principal.member_id,
                                                     revision=revision).on_conflict_do_nothing())
    return {"asset_id": asset.id, "revision": revision, "current_revision": asset.evidence_revision}


def delete(db: Session, asset: VideoAsset) -> dict[str, Any]:
    """Remove the clip's bytes. Measurements stay (numbers, no imagery), marked
    as belonging to a deleted clip. Bytes shared with another family's asset
    (same content) stay until that one is deleted too."""
    if asset.deleted_at is not None:
        return {"asset_id": asset.id, "deleted": True, "bytes_removed": False}
    asset.deleted_at = func.now()
    db.execute(select(func.pg_advisory_xact_lock(func.hashtext(asset.storage_key))))
    others = db.execute(select(func.count()).select_from(VideoAsset).where(
        VideoAsset.storage_key == asset.storage_key, VideoAsset.id != asset.id,
        VideoAsset.deleted_at.is_(None))).scalar_one()
    removed = False
    if others == 0:
        path = media_root() / asset.storage_key
        if path.is_file():
            try:
                path.unlink()
                removed = True
            except OSError:                        # still open (a stream or an analysis on Windows)
                removed = False
    return {"asset_id": asset.id, "deleted": True, "bytes_removed": removed,
            "note": None if removed or others else "the bytes are in use; the clip is already unreachable"}


# ---------------------------------------------------------------- signed media links

def media_token(principal: Principal, asset: VideoAsset, now: Optional[float] = None) -> tuple[str, int]:
    expires = int((now or time.time()) + MEDIA_TOKEN_TTL.total_seconds())
    body = f"{asset.id}.{principal.member_id}.{expires}"
    sig = hmac.new(SECRET, ("media:" + body).encode(), hashlib.sha256).hexdigest()[:40]
    return f"{body}.{sig}", expires


def check_media_token(token: str, asset_id: str, now: Optional[float] = None) -> str:
    """The member a valid, unexpired token was minted for. Raises otherwise."""
    try:
        token_asset, member_id, expires, sig = token.split(".")
        body = f"{token_asset}.{member_id}.{expires}"
        good = hmac.new(SECRET, ("media:" + body).encode(), hashlib.sha256).hexdigest()[:40]
        valid = hmac.compare_digest(sig.encode(), good.encode()) and token_asset == asset_id
        expired = int(expires) < (now or time.time())
    except (ValueError, UnicodeEncodeError):       # malformed, or not ASCII: invalid, never a 500
        valid, expired = False, False
    if not valid:
        raise DomainError(404, "NOT_FOUND", "media not found")
    if expired:
        raise DomainError(401, "MEDIA_LINK_EXPIRED", "this media link has expired; reopen the evidence view")
    return member_id
