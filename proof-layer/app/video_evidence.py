def upload_limits() -> vp.Limits:
    return vp.Limits(max_bytes=int(os.environ.get("PROOF_LAYER_MAX_UPLOAD_BYTES", str(64 * 1024 * 1024))))


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _media_error(exc: vp.MediaError) -> DomainError:
    status = 413 if exc.code == "TOO_LARGE" else 422
    return DomainError(status, exc.code, exc.message, **exc.detail)


# ---------------------------------------------------------------- the gate

def gate(db: Session, household: Household, device: Device) -> dict[str, Any]:
    """Whether this camera's plan includes the capability the evidence view
    rests on, evaluated by the same rules as every feature decision."""
    catalog_version, policy_version = decisions.active_versions(db)
    plan = claims.camera_plan(db, household.id, device.id, catalog_version)
    result = entitlements.evaluate(feature=GATE_FEATURE, plan_code=plan["plan_code"], mounts=[device.mount],
                                   catalog_version=catalog_version, policy_version=policy_version, with_offer=False)
    return {"feature": GATE_FEATURE, "label": entitlements.POLICIES[policy_version]["features"][GATE_FEATURE]["label"],
            "allowed": result["status"] == "AVAILABLE", "status": result["status"], "plan_code": plan["plan_code"],
            "plan_label": plan["plan_label"],
            "blockers": [{"code": b["code"], "parent_message": b.get("parent_message")} for b in result["blockers"]],
            "rule": "assumed public plan rule (app/entitlements.py), not Nanit's internal entitlement"}


def require_gate(db: Session, household: Household, device: Device, *, record: bool) -> dict[str, Any]:
    """Refuse unless the gate is open. Commands record the check (a capability
    verified, or refused); reads don't write."""
    g = gate(db, household, device)
    if record:
        growth.record_server(db, "evidence_access_checked", household.id,
                             {"device_id": device.id, "allowed": g["allowed"]})
    if not g["allowed"]:
        raise DomainError(403, "FEATURE_NOT_IN_PLAN", f"{g['label']} isn't included in this camera's plan",
                          gate=g)
    return g


