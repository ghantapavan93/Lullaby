"""Video evidence: a real clip, measured by the worker, read and annotated by
the family, and gated by the camera's plan.

States are kept apart and never inferred from one another:
- the clip is stored (video_assets);
- the analysis is a durable run whose state the worker advances
  (REGISTERED -> VALIDATING -> ANALYZING -> COMPLETED, or FAILED with a
  code). The outbox only delivers the work. Decode and analysis are one
  streaming pass;
- measured intervals are written once, in the run's final transaction
  (video_observations);
- what a person reports is a separate, append-only record with its own
  revision (video_annotations); a measurement is never edited because a
  person disagreed with it;
- seeing a revision is an acknowledgment of that revision only.

Access: reading the evidence needs the camera's plan to include 7-day video
history (an assumed public plan rule, app/entitlements.py), checked on every
read. Media bytes are served only through a short-lived signed link minted
after that check. They are never in a static directory.

Synthetic and local: the household, camera and plan are synthetic. The clip
is either a CC0 sample kept local-only or a generated staged clip.
"""
